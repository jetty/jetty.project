package org.eclipse.jetty.quic.server.internal;

import java.util.ArrayList;
import java.util.List;

import org.eclipse.jetty.io.CyclicTimeouts;
import org.eclipse.jetty.io.RetainableByteBuffer;
import org.eclipse.jetty.quic.api.Session;
import org.eclipse.jetty.quic.api.frames.CryptoFrame;
import org.eclipse.jetty.quic.api.frames.Frame;
import org.eclipse.jetty.quic.api.frames.HandshakeDoneFrame;
import org.eclipse.jetty.quic.api.frames.NewTokenFrame;
import org.eclipse.jetty.quic.api.frames.TransportParameters;
import org.eclipse.jetty.quic.api.tls.ext.QuicTransportParametersExtension;
import org.eclipse.jetty.quic.common.EncryptionLevel;
import org.eclipse.jetty.quic.common.PacketTracker;
import org.eclipse.jetty.quic.common.QuicSession;
import org.eclipse.jetty.quic.common.packets.InitialPacket;
import org.eclipse.jetty.quic.common.packets.Packet;
import org.eclipse.jetty.quic.common.packets.PacketNumbers;
import org.eclipse.jetty.quic.common.packets.PacketProtector;
import org.eclipse.jetty.quic.common.packets.RetryPacket;
import org.eclipse.jetty.quic.common.tls.HandshakeData;
import org.eclipse.jetty.quic.common.tls.TLSEngine;
import org.eclipse.jetty.quic.server.QuicServerQuicConfiguration;
import org.eclipse.jetty.quic.server.internal.tls.ServerTLSEngine;
import org.eclipse.jetty.quic.util.ErrorCode;
import org.eclipse.jetty.quic.util.QuicException;
import org.eclipse.jetty.server.Connector;
import org.eclipse.jetty.tls.CertificateMessage;
import org.eclipse.jetty.tls.CertificateVerifyMessage;
import org.eclipse.jetty.tls.ClientHelloMessage;
import org.eclipse.jetty.tls.FinishedMessage;
import org.eclipse.jetty.tls.Message;
import org.eclipse.jetty.util.Callback;
import org.eclipse.jetty.util.thread.Invocable;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/// The server-specific implementation of [QuicSession].
public class ServerQuicSession extends QuicSession implements CyclicTimeouts.Expirable
{
    private static final Logger LOG = LoggerFactory.getLogger(ServerQuicSession.class);

    private long expireNanoTime = Long.MAX_VALUE;
    private boolean retryPacketSent;

    public ServerQuicSession(Connector connector, QuicServerQuicConfiguration configuration, ServerQuicConnection connection, PacketTracker packetTracker, PacketNumbers packetNumbers, ServerTLSEngine tlsEngine, Session.Listener listener)
    {
        super(connector.getExecutor(), connector.getScheduler(), connector.getByteBufferPool(), configuration, connection, packetTracker, packetNumbers, tlsEngine, listener, false);
        // Link the ServerTLSEngine back to this session to
        // send the TLS messages generated by ServerTLSEngine.
        tlsEngine.addMessageListener(new TLSEngine.MessageListener()
        {
            @Override
            public void onOutgoingMessages(EncryptionLevel encryptionLevel, List<Message> messages, Callback callback)
            {
                sendTLSMessages(encryptionLevel, messages, callback);
            }
        });

        // Link the ServerTLSEngine back to this session to
        // be notified when the TLS handshake is complete.
        tlsEngine.addHandshakeListener(this::handshakeComplete);
    }

    @Override
    public QuicServerQuicConfiguration getQuicConfiguration()
    {
        return (QuicServerQuicConfiguration)super.getQuicConfiguration();
    }

    @Override
    public ServerTLSEngine getTLSEngine()
    {
        return (ServerTLSEngine)super.getTLSEngine();
    }

    @Override
    public ServerQuicConnection getQuicConnection()
    {
        return (ServerQuicConnection)super.getQuicConnection();
    }

    void initialize(byte[] dstConnectionId)
    {
        PacketProtector packetProtector = getTLSEngine().getPacketProtector();
        packetProtector.generateInitialKeys(getQuicVersion(), dstConnectionId);
        getTLSEngine().initialize(getQuicVersion());
    }

    @Override
    public void setIdleTimeout(long idleTimeout)
    {
        super.setIdleTimeout(idleTimeout);
        notIdle();
        getQuicConnection().schedule(this);
    }

    @Override
    public long getExpireNanoTime()
    {
        return expireNanoTime;
    }

    protected void notIdle()
    {
        expireNanoTime = CyclicTimeouts.Expirable.calcExpireNanoTime(getIdleTimeout());
    }

    @Override
    public int getUDPPayloadLength()
    {
        return getQuicConfiguration().getUDPPayloadLength();
    }

    @Override
    protected InitialPacket newInitialPacket(List<Frame> frames)
    {
        // TODO: token creation and validation.
        byte[] token = new byte[0];
        return new InitialPacket(getQuicVersion(), getDestinationConnectionId(), getSourceConnectionId(), token, getPacketNumbers().nextPacketNumber(EncryptionLevel.INITIAL), frames);
    }

    @Override
    protected List<Invocable.Task> processPacket(Packet packet)
    {
        try
        {
            return switch (packet)
            {
                case InitialPacket initialPacket ->
                {
                    if (processInitialPacket(initialPacket))
                        yield super.processPacket(packet);
                    yield List.of();
                }
                default -> super.processPacket(packet);
            };
        }
        catch (Throwable x)
        {
            fail(x);
            return List.of();
        }
    }

    private boolean processInitialPacket(InitialPacket packet) throws Exception
    {
        if (packet.frames().getFirst() instanceof CryptoFrame)
        {
            byte[] token = packet.token();
            if (token == null || token.length == 0)
            {
                if (LOG.isDebugEnabled())
                    LOG.debug("no token in {} on {}", packet, this);

                // Store the odcid to be used for the next InitialPacket and for the RetryPacket.
                byte[] origDstConnectionId = packet.destinationConnectionId();
                setOriginalDestinationConnectionId(origDstConnectionId);

                token = getQuicConfiguration().getTokenFactory().newRetryToken(getRemoteSocketAddress(), origDstConnectionId);
                // RFC-9000[17.2.5.1]: retry.dst=pkt.src; retry.src!=pkt.dst.
                RetryPacket retryPacket = new RetryPacket(packet.quicVersion(), packet.sourceConnectionId(), getSourceConnectionId(), token, null);
                RetainableByteBuffer.Mutable retryAccumulator = new RetainableByteBuffer.DynamicCapacity(getByteBufferPool(), false, -1, 0, 0);
                generateRetryPacket(retryAccumulator, retryPacket);
                byte[] integrity = getTLSEngine().createRetryIntegrity(retryAccumulator, origDstConnectionId);
                retryPacketSent = true;
                retryPacket = retryPacket.withIntegrity(integrity);
                packet(retryPacket, Callback.NOOP);

                if (LOG.isDebugEnabled())
                    LOG.debug("dropping {} on {}", packet, this);
                return false;
            }

            TransportParameters transportParameters = getTLSEngine().getTLSConfiguration().getTransportParameters();
            if (retryPacketSent)
                transportParameters.put(TransportParameters.Ids.RETRY_SOURCE_CONNECTION_ID, getSourceConnectionId());
            notifyPrepare(transportParameters);

            boolean valid = getQuicConfiguration().getTokenFactory().isTokenValid(getRemoteSocketAddress(), getOriginalDestinationConnectionId(), token);
            if (LOG.isDebugEnabled())
                LOG.debug("token {} in {} on {}", valid ? "valid" : "invalid", packet, this);
            if (!valid)
                throw new QuicException(ErrorCode.INVALID_TOKEN_ERROR, "invalid_token");
        }
        return true;
    }

    @Override
    protected void processMessage(Message message)
    {
        switch (message)
        {
            case ClientHelloMessage clientHello -> processClientHello(clientHello);
            case CertificateMessage certificate -> getTLSEngine().onMessage(EncryptionLevel.HANDSHAKE, certificate);
            case CertificateVerifyMessage certificateVerify -> getTLSEngine().onMessage(EncryptionLevel.HANDSHAKE, certificateVerify);
            case FinishedMessage finished -> getTLSEngine().onMessage(EncryptionLevel.HANDSHAKE, finished);
            default -> throw new IllegalStateException("unexpected message " + message);
        }
    }

    private void processClientHello(ClientHelloMessage clientHello)
    {
        TransportParameters transportParameters = clientHello.extensions().stream()
            .filter(ext -> ext instanceof QuicTransportParametersExtension)
            .map(QuicTransportParametersExtension.class::cast)
            .findFirst()
            .map(QuicTransportParametersExtension::transportParameters)
            .orElse(null);

        processTransportParameters(transportParameters);

        getTLSEngine().onMessage(EncryptionLevel.INITIAL, clientHello);
    }

    private void handshakeComplete(HandshakeData data, Throwable failure)
    {
        if (failure == null)
            handshakeSuccessful(data);
        else
            handshakeFailure(failure);
    }

    private void handshakeSuccessful(HandshakeData data)
    {
        try
        {
            notifyOpen();
            List<Frame> frames = new ArrayList<>();
            frames.add(new HandshakeDoneFrame());
            byte[] token = getQuicConfiguration().getTokenFactory().newToken(getRemoteSocketAddress());
            frames.add(new NewTokenFrame(token));
            // TODO: send also NewConnectionIdFrames.
            frames(frames, Callback.from(() -> {}, this::fail));
        }
        catch (Throwable x)
        {
            fail(x);
        }
    }

    private void handshakeFailure(Throwable failure)
    {
        fail(failure);
    }
}
